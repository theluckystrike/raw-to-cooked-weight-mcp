#!/usr/bin/env python3
"""Write src/data.ts from data/cooking-yields.json so both the Node and Worker builds embed the table."""
import json, sys
d = json.load(open(sys.argv[1]))
with open(sys.argv[2], 'w') as f:
    f.write('// Generated by scripts/gen_ts.py from data/cooking-yields.json. Do not edit.\n')
    f.write('import type { YieldRow } from \'./types.js\';\n\n')
    f.write('export const YIELDS: YieldRow[] = ' + json.dumps(d['items'], separators=(',', ':')) + ';\n')
